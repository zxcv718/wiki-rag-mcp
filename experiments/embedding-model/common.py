    """맥락 헤더를 붙인 약 target 토큰짜리 청크 n개를 만든다."""
    chunks = []
    for i in range(n):
        head = f"사내 위키 > 문서 {i} > 섹션 {i % 7}\n"
        body, j = "", i
        while len(tokenizer(head + body)["input_ids"]) < target:
            body += BASE[j % len(BASE)] + " "
            j += 1
        chunks.append(head + body)
    return chunks
